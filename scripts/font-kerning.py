"""Make src/text/font-kerning.ts: the kerning pairs of the Liberation fonts.

The Liberation fonts (SIL Open Font License 1.1) kern the same letter pairs by the same amounts
as Times New Roman and Arial (checked against Word's PDF of a document: "Te" -0.85 pt at 12 pt,
Liberation -0.84), so documents measured with these pairs break their lines where Word does when
it kerns (Word's Kerning for fonts, w:kern).

Run with Python 3 and fontTools (pip install fonttools):
    python scripts/font-kerning.py /usr/share/fonts/truetype/liberation
Only the pair amounts are taken; no part of the fonts themselves is copied.
"""

import sys
from collections import defaultdict
from pathlib import Path

from fontTools.ttLib import TTFont

FAMILIES = {'serif': 'LiberationSerif', 'sans': 'LiberationSans'}
STYLES = {'': 'Regular', 'b': 'Bold', 'i': 'Italic', 'bi': 'BoldItalic'}
# pairs of the letters, digits and punctuation documents use (Basic Latin and Latin-1)
CHARS = [c for c in range(0x20, 0x7F)] + [c for c in range(0xA0, 0x100)]


def pairs(path: Path) -> dict[tuple[int, int], int]:
    font = TTFont(path)
    cmap = font.getBestCmap()
    glyph_chars = defaultdict(list)
    for c in CHARS:
        g = cmap.get(c)
        if g is not None:
            glyph_chars[g].append(c)
    found: dict[tuple[str, str], int] = {}
    gpos = font['GPOS'].table if 'GPOS' in font else None
    for lookup in (gpos.LookupList.Lookup if gpos else []):
        for sub in lookup.SubTable:
            if lookup.LookupType == 9:
                sub = sub.ExtSubTable
            if getattr(sub, 'LookupType', lookup.LookupType) != 2:
                continue
            cov = sub.Coverage.glyphs
            if sub.Format == 1:
                for i, ps in enumerate(sub.PairSet):
                    for rec in ps.PairValueRecord:
                        v = getattr(rec.Value1, 'XAdvance', 0) if rec.Value1 else 0
                        if v:
                            found.setdefault((cov[i], rec.SecondGlyph), v)
            else:
                c1 = sub.ClassDef1.classDefs if sub.ClassDef1 else {}
                by_class = defaultdict(list)
                for g, k in sub.ClassDef2.classDefs.items():
                    by_class[k].append(g)
                for g1 in cov:
                    rec = sub.Class1Record[c1.get(g1, 0)]
                    for k2, r2 in enumerate(rec.Class2Record):
                        v = getattr(r2.Value1, 'XAdvance', 0) if r2.Value1 else 0
                        if v and k2 in by_class:
                            for g2 in by_class[k2]:
                                found.setdefault((g1, g2), v)
    if 'kern' in font and not found:
        for table in font['kern'].kernTables:
            for (g1, g2), v in table.kernTable.items():
                if v:
                    found.setdefault((g1, g2), v)
    out = {}
    for (g1, g2), v in found.items():
        for a in glyph_chars.get(g1, []):
            for b in glyph_chars.get(g2, []):
                out[(a, b)] = v
    return out


def encode(p: dict[tuple[int, int], int]) -> str:
    """Pairs by first character: "first (hex):second (hex)=amount,…;…"."""
    by_first = defaultdict(list)
    for (a, b), v in sorted(p.items()):
        by_first[a].append(f'{b:x}={v}')
    return ';'.join(f'{a:x}:' + ','.join(v) for a, v in sorted(by_first.items()))


def main() -> None:
    folder = Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation')
    tables = {}
    for fam, base in FAMILIES.items():
        for key, style in STYLES.items():
            tables[fam + key] = encode(pairs(folder / f'{base}-{style}.ttf'))
    lines = [
        '// Generated by scripts/font-kerning.py: do not edit by hand.',
        '// Kerning pairs of the Liberation fonts (SIL Open Font License 1.1, see THIRD-PARTY-NOTICES.md),',
        '// which kern as Times New Roman and Arial do, in units of UNITS_PER_EM (font-widths.ts).',
        '// Each table: "first (hex):second (hex)=amount,…;…".',
        '',
        'export const KERN_TABLES: Record<string, string> = {',
    ]
    for k, v in tables.items():
        lines.append(f"  '{k}': '{v}',")
    lines.append('};')
    lines.append('')
    out = Path(__file__).resolve().parent.parent / 'src' / 'text' / 'font-kerning.ts'
    out.write_text('\n'.join(lines), encoding='utf-8')
    print(out, sum(len(v) for v in tables.values()), 'characters of tables')


if __name__ == '__main__':
    main()
