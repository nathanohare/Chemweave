// The desktop app only lets the page call the Tauri commands its capability files
// (src-tauri/capabilities/*.json) allow; anything else fails at run time with "Command ... not
// allowed by ACL", which no web test sees. File > Print on the Mac failed that way: window.print()
// is routed by Tauri to plugin:webview|print, which core:default does not allow.
//
// This test reads the app's own code for every Tauri command it can reach (through the
// @tauri-apps/* functions it calls, followed into those packages' own code, and window.print), and
// checks each one is allowed. It errs on the side of asking for too much: a call named like a
// Tauri function in a file that uses that part of Tauri counts. It also checks every command the
// app invokes by name is registered in the desktop app (generate_handler! in src-tauri/src).
import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import ts from 'typescript';

const ROOT = join(__dirname, '..');
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8');

// What each `default` permission set allows, from Tauri's permission references for the versions
// in src-tauri/Cargo.lock (the "Default Permission" section of each):
// https://github.com/tauri-apps/tauri/tree/tauri-v2.12.3/crates/tauri/permissions/<plugin>/autogenerated/reference.md
// https://github.com/tauri-apps/plugins-workspace/tree/<plugin>-v<version>/plugins/<plugin>/permissions/autogenerated/reference.md
// When one of these crates moves to a new minor version, re-check its list and update the version.
const DEFAULTS: Record<string, { crate: string; version: string; allow: string[] }> = {
  'core:window': {
    crate: 'tauri', version: '2.12',
    allow: ['get-all-windows', 'scale-factor', 'inner-position', 'outer-position', 'inner-size', 'outer-size', 'is-fullscreen', 'is-minimized', 'is-maximized', 'is-focused', 'is-decorated', 'is-resizable', 'is-maximizable', 'is-minimizable', 'is-closable', 'is-visible', 'is-enabled', 'title', 'current-monitor', 'primary-monitor', 'monitor-from-point', 'available-monitors', 'cursor-position', 'theme', 'is-always-on-top', 'activity-name', 'scene-identifier', 'internal-toggle-maximize'],
  },
  'core:webview': { crate: 'tauri', version: '2.12', allow: ['get-all-webviews', 'webview-position', 'webview-size', 'internal-toggle-devtools'] },
  'core:event': { crate: 'tauri', version: '2.12', allow: ['listen', 'unlisten', 'emit', 'emit-to'] },
  'core:app': { crate: 'tauri', version: '2.12', allow: ['version', 'name', 'tauri-version', 'identifier', 'bundle-type', 'register-listener', 'remove-listener', 'supports-multiple-windows'] },
  'core:resources': { crate: 'tauri', version: '2.12', allow: ['close'] },
  'core:path': { crate: 'tauri', version: '2.12', allow: ['resolve-directory', 'resolve', 'normalize', 'join', 'dirname', 'extname', 'basename', 'is-absolute'] },
  dialog: { crate: 'tauri-plugin-dialog', version: '2.8', allow: ['message', 'save', 'open'] },
  opener: { crate: 'tauri-plugin-opener', version: '2.7', allow: ['open-url', 'reveal-item-in-dir', 'default-urls'] },
  process: { crate: 'tauri-plugin-process', version: '2.4', allow: ['exit', 'restart'] },
  updater: { crate: 'tauri-plugin-updater', version: '2.14', allow: ['check', 'download', 'install', 'download-and-install'] },
};
/** core:default is the default set of each core part (Tauri's core permissions reference). */
const CORE_PARTS = ['app', 'event', 'image', 'menu', 'path', 'resources', 'tray', 'webview', 'window'];

/** Commands Tauri routes page functions to by itself (not through @tauri-apps/api). */
const BUILT_IN: { pattern: RegExp; command: string }[] = [
  // wry's macOS and Linux webviews have no print of their own; Tauri sends window.print() here
  { pattern: /\bwindow\.print\s*\(/, command: 'plugin:webview|print' },
];

type Unit = { invokes: Set<string>; calls: string[][] };
type PackageFile = { units: Map<string, Unit[]>; scope: string[] };

/**
 * Where a call in package code can go, most exact first: `this.x()` in class C to `C.x`,
 * `super.x()` to the parent's `x`, anything else to a function or method named `x`.
 */
function callTargets(n: ts.CallExpression, cls?: ts.ClassDeclaration): string[] | undefined {
  const e = n.expression;
  if (ts.isIdentifier(e)) return [e.text];
  if (!ts.isPropertyAccessExpression(e)) return undefined;
  const name = e.name.text;
  if (e.expression.kind === ts.SyntaxKind.ThisKeyword && cls?.name) return [`${cls.name.text}.${name}`, name];
  if (e.expression.kind === ts.SyntaxKind.SuperKeyword) {
    const parent = cls?.heritageClauses?.[0]?.types[0]?.expression;
    if (parent && ts.isIdentifier(parent)) return [`${parent.text}.${name}`, name];
  }
  return [name];
}

const fileCache = new Map<string, PackageFile>();
/**
 * A package file's functions and methods, keyed `name` and `Class.name` (`new Class` for a
 * constructor), each with the commands it invokes and what it calls; and the files its calls can
 * reach (itself and what it imports).
 */
function packageFile(file: string): PackageFile {
  const cached = fileCache.get(file);
  if (cached) return cached;
  const src = ts.createSourceFile(file, read(file), ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const units = new Map<string, Unit[]>();
  const add = (keys: string[], body: ts.Node | undefined, cls?: ts.ClassDeclaration) => {
    if (!body) return;
    const u: Unit = { invokes: new Set(), calls: [] };
    const visit = (n: ts.Node): void => {
      if (ts.isCallExpression(n)) {
        const a = n.arguments[0];
        if (ts.isIdentifier(n.expression) && n.expression.text === 'invoke' && a && ts.isStringLiteralLike(a) && a.text.startsWith('plugin:')) u.invokes.add(a.text);
        // a package's own `new Window(label, { skip: true })` only wraps an existing window, so
        // constructors are followed only when the app itself calls them
        const t = callTargets(n, cls);
        if (t) u.calls.push(t);
      }
      ts.forEachChild(n, visit);
    };
    visit(body);
    for (const k of keys) units.set(k, [...(units.get(k) ?? []), u]);
  };
  const clsOf = (n: ts.Node) => (n.parent && ts.isClassDeclaration(n.parent) ? n.parent : undefined);
  const visit = (n: ts.Node): void => {
    const cls = clsOf(n);
    if (ts.isFunctionDeclaration(n) && n.name) add([n.name.text], n.body);
    else if ((ts.isMethodDeclaration(n) || ts.isGetAccessor(n)) && ts.isIdentifier(n.name)) add([n.name.text, `${cls?.name?.text}.${n.name.text}`], n.body, cls);
    else if (ts.isConstructorDeclaration(n) && cls?.name) add([`new ${cls.name.text}`], n.body, cls);
    else if (ts.isVariableDeclaration(n) && ts.isIdentifier(n.name) && n.initializer && (ts.isArrowFunction(n.initializer) || ts.isFunctionExpression(n.initializer))) add([n.name.text], n.initializer.body);
    ts.forEachChild(n, visit);
  };
  visit(src);
  const scope = [file];
  for (const m of src.text.matchAll(/^(?:import|export)\b[^;]*?\bfrom\s+'([^']+)'/gm)) {
    const spec = m[1];
    const target = spec.startsWith('.') ? join(file, '..', spec) : spec.startsWith('@tauri-apps/api/') ? `node_modules/${spec}.js` : undefined;
    if (target && !target.includes('/external/')) scope.push(target);
  }
  const pf = { units, scope };
  fileCache.set(file, pf);
  return pf;
}

/** Every command a call to one of these targets can reach, followed through the packages. */
function reach(targets: string[], scope: string[], seen = new Set<string>()): Set<string> {
  const out = new Set<string>();
  for (const key of targets) {
    const hits = scope.flatMap((f) => (packageFile(f).units.get(key) ?? []).map((u) => ({ u, f })));
    if (!hits.length) continue;
    for (const { u, f } of hits) {
      const id = `${f}#${key}`;
      if (seen.has(id)) continue;
      seen.add(id);
      u.invokes.forEach((c) => out.add(c));
      for (const t of u.calls) reach(t, packageFile(f).scope, seen).forEach((x) => out.add(x));
    }
    break; // the most exact target found settles it
  }
  return out;
}

/** Each Tauri command the app's code can reach, with the files that reach it. */
/** Functions Tauri hands back, typed only by a type: the commands they reach. */
const TYPE_COMMANDS: Record<string, string[]> = {
  // event.js: listen() resolves to () => _unlisten(event, id), which invokes plugin:event|unlisten
  UnlistenFn: ['plugin:event|unlisten'],
};

let usedCache: Map<string, Set<string>> | undefined;
/** Calls into @tauri-apps that this test could not follow into the package's code. */
const unfollowed = new Set<string>();
function commandsUsed(): Map<string, Set<string>> {
  if (usedCache) return usedCache;
  const used = new Map<string, Set<string>>();
  const note = (cmd: string, file: string) => used.set(cmd, (used.get(cmd) ?? new Set()).add(file));
  const config = ts.getParsedCommandLineOfConfigFile(join(ROOT, 'tsconfig.json'), {}, { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => {} })!;
  const program = ts.createProgram(config.fileNames, { ...config.options, noEmit: true });
  const checker = program.getTypeChecker();
  for (const sf of program.getSourceFiles()) {
    if (sf.isDeclarationFile || !sf.fileName.startsWith(join(ROOT, 'src'))) continue;
    const file = sf.fileName.slice(ROOT.length + 1);
    for (const b of BUILT_IN) if (b.pattern.test(sf.text)) note(b.command, file);
    if (!sf.text.includes('@tauri-apps/')) continue;
    const visit = (n: ts.Node): void => {
      if (ts.isCallExpression(n) || ts.isNewExpression(n)) {
        const decl = checker.getResolvedSignature(n)?.declaration;
        const where = decl?.getSourceFile().fileName ?? '';
        if (decl && where.includes('/node_modules/@tauri-apps/')) {
          const id = ts.getNameOfDeclaration(decl as ts.Declaration);
          const name = id && ts.isIdentifier(id) ? id.text : undefined;
          const owner = decl.parent && (ts.isClassDeclaration(decl.parent) || ts.isInterfaceDeclaration(decl.parent)) && decl.parent.name ? decl.parent.name.text : undefined;
          const key = ts.isConstructorDeclaration(decl) || ts.isConstructSignatureDeclaration(decl) ? `new ${owner}` : owner ? `${owner}.${name}` : name;
          const js = where.slice(where.indexOf('node_modules/')).replace(/\.d\.ts$/, '.js');
          const scope = packageFile(js).scope;
          const alias = decl.parent && ts.isTypeAliasDeclaration(decl.parent) ? TYPE_COMMANDS[decl.parent.name.text] : undefined;
          if (alias) alias.forEach((c) => note(c, file));
          else if (!key || !scope.some((f) => packageFile(f).units.has(key))) unfollowed.add(`${key ?? n.getText()} (${file})`);
          else reach([key], scope).forEach((c) => note(c, file));
        }
      }
      ts.forEachChild(n, visit);
    };
    visit(sf);
  }
  usedCache = used;
  return used;
}

function sourceFiles(dir: string): string[] {
  return readdirSync(join(ROOT, dir)).flatMap((f) => {
    const p = `${dir}/${f}`;
    if (statSync(join(ROOT, p)).isDirectory()) return sourceFiles(p);
    return /\.tsx?$/.test(f) && !f.endsWith('.d.ts') ? [p] : [];
  });
}

/** The permission that allows a plugin command, e.g. plugin:window|set_title -> core:window:allow-set-title. */
function permissionFor(cmd: string): string {
  const m = /^plugin:([\w-]+)\|(\w+)$/.exec(cmd);
  if (!m) throw new Error(`not a plugin command: ${cmd}`);
  const plugin = CORE_PARTS.includes(m[1]) ? `core:${m[1]}` : m[1];
  return `${plugin}:allow-${m[2].replace(/_/g, '-')}`;
}

/** Every permission the capability files grant, with default sets expanded. */
function allowed(): Set<string> {
  const out = new Set<string>();
  const expand = (id: string) => {
    if (id === 'core:default') return CORE_PARTS.forEach((p) => expand(`core:${p}:default`));
    const def = /^(.*):default$/.exec(id);
    if (def) return (DEFAULTS[def[1]]?.allow ?? []).forEach((a) => out.add(`${def[1]}:allow-${a}`));
    out.add(id);
  };
  const dir = 'src-tauri/capabilities';
  for (const f of readdirSync(join(ROOT, dir)).filter((f) => f.endsWith('.json'))) {
    const cap = JSON.parse(read(`${dir}/${f}`)) as { permissions: (string | { identifier: string })[] };
    for (const p of cap.permissions) expand(typeof p === 'string' ? p : p.identifier);
  }
  return out;
}

describe('Tauri permissions', () => {
  it('the default-set lists match the Tauri versions the desktop app is built with', () => {
    const lock = read('src-tauri/Cargo.lock');
    for (const [set, d] of Object.entries(DEFAULTS)) {
      const m = new RegExp(`name = "${d.crate}"\\nversion = "(\\d+\\.\\d+)\\.`).exec(lock);
      expect(m?.[1], `${d.crate} for ${set}:default`).toBe(d.version);
    }
  });

  it('finds the commands it is meant to find', { timeout: 120_000 }, () => {
    const used = commandsUsed();
    // a few the app is known to use, so the search itself can't quietly stop finding anything
    expect([...unfollowed], 'calls into Tauri this test cannot follow: teach packageFile() their shape').toEqual([]);
    for (const c of ['plugin:webview|print', 'plugin:window|set_title', 'plugin:dialog|open', 'plugin:event|listen', 'plugin:webview|create_webview_window']) {
      expect([...used.keys()], c).toContain(c);
    }
  });

  it('every Tauri command the app can reach is allowed by a capability file', { timeout: 120_000 }, () => {
    const ok = allowed();
    const missing = [...commandsUsed()]
      .filter(([cmd]) => !ok.has(permissionFor(cmd)))
      .map(([cmd, files]) => `${permissionFor(cmd)} (${cmd}, from ${[...files].join(', ')})`);
    expect(missing, 'add these to src-tauri/capabilities/default.json, or stop calling them').toEqual([]);
  });

  it('every command the app invokes by name is registered in the desktop app', () => {
    const rust = sourceFilesRust('src-tauri/src').map(read).join('\n');
    const registered = new Set(
      [...rust.matchAll(/generate_handler!\s*\[([^\]]*)\]/g)].flatMap((m) =>
        m[1].split(',').map((s) => s.replace(/#\[[^\]]*\]/g, '').trim().split('::').pop()!).filter(Boolean)),
    );
    expect(registered.size).toBeGreaterThan(10);
    const missing = new Set<string>();
    for (const file of sourceFiles('src')) {
      for (const m of read(file).matchAll(/\binvoke(?:<[^>(]*(?:<[^>]*>[^>(]*)*>)?\(\s*'([a-z_0-9]+)'/g)) {
        if (!registered.has(m[1])) missing.add(`${m[1]} (${file})`);
      }
    }
    expect([...missing]).toEqual([]);
  });
});

function sourceFilesRust(dir: string): string[] {
  return readdirSync(join(ROOT, dir)).flatMap((f) => {
    const p = `${dir}/${f}`;
    if (statSync(join(ROOT, p)).isDirectory()) return sourceFilesRust(p);
    return f.endsWith('.rs') ? [p] : [];
  });
}
